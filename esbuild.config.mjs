import builtins from "builtin-modules";
import esbuild from "esbuild";
import process from "process";
import { noticeBanner } from "./third-party-notices.mjs";

// The licence notices of the bundled packages (d3: ISC and BSD-3-Clause, React and Preact signals: MIT) must ship
// with every copy of main.js; see third-party-notices.mjs and THIRD_PARTY_NOTICES.md.
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
${noticeBanner()}`;

const prod = process.argv[2] === "production";

const ctx = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: true,
  outfile: "main.js",
});

if (process.argv[2] === "watch") {
  await ctx.watch();
  console.log("⚡ Watch mode enabled - rebuilding on file changes...");
} else {
  await ctx.rebuild();
  await ctx.dispose();
}
